const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const vm = require('node:vm');
const js = ts.transpileModule(fs.readFileSync('src/lib/effectiveHealthSummary.ts','utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
const ctx={exports:{}};vm.runInNewContext(js,ctx);
const calc=ctx.exports.effectiveHealthSummaries;
const now=Date.now();
const state={summaries:[{id:'A2',title:'ROS',status:'DEGRADED',summary:'host hot',reason_item_id:'host'}],domains:[{id:'H2',items:[{id:'host',status:'DEGRADED',critical:true,summary:'host hot'},{id:'clock',status:'OK',critical:true,summary:'clock advancing'}]}]};
const recovery={generated_at:new Date(now).toISOString(),robot_health_summary:{items:[{item:'host',ignored:true,level:'OK',observed_level:'WARN'}]}};
const before=JSON.stringify(state);
assert.equal(calc(state,recovery,now)[0].status,'AVAILABLE');
assert.equal(JSON.stringify(state),before);
state.domains[0].items[1].status='WARN';
assert.equal(calc(state,recovery,now)[0].reason_item_id,'clock');
state.domains[0].items[1].status='OK';
state.domains[0].items[0].status='ERROR';
assert.equal(calc(state,recovery,now)[0].status,'DEGRADED');
state.domains[0].items[0].status='DEGRADED';
assert.equal(calc(state,recovery,now+11000)[0].status,'DEGRADED');
recovery.robot_health_summary.items=[];
assert.equal(calc(state,recovery,now)[0].status,'DEGRADED');
assert.equal(calc(state,null,now)[0].status,'DEGRADED');
console.log('Effective summary: ignored WARN, new WARN, BAD escalation, expiry, restore, immutable raw evidence passed');
